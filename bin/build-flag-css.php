<?php
/**
 * Regenerate public/css/phone-flags.css from the vendored intl-tel-input
 * stylesheet. Run after every upgrade of public/lib/intl-tel-input:
 *
 *     php bin/build-flag-css.php
 *
 * Why the file exists at all: upstream picks a flag with
 * `calc(var(--iti-flag-offset) * var(--iti-flag-width))`, on bare `.iti__lt`
 * selectors. A site that also loads an older copy of the picker (other form
 * plugins bundle one) redefines --iti-flag-offset in pixels, the calc() becomes
 * invalid, and every flag falls back to the first in the sprite — Ascension
 * Island. The generated table says the same thing under .send4-iti, with
 * variables nobody else writes, so it wins wherever it loads.
 *
 * tests/Unit/PhoneFlagCssTest.php fails when the committed file and this
 * script's output drift apart.
 *
 * @package Send4
 */

if ( 'cli' !== PHP_SAPI && ! defined( 'SEND4_FLAG_CSS_AS_LIBRARY' ) ) {
	exit( 1 );
}

/**
 * The stylesheet, as a string.
 *
 * @param string $root Plugin root.
 * @return string
 */
function send4_build_flag_css( $root ) {
	$source = file_get_contents( $root . '/public/lib/intl-tel-input/css/intlTelInput.css' );

	if ( false === $source ) {
		throw new RuntimeException( 'Cannot read the vendored intlTelInput.css.' );
	}

	if ( 1 !== preg_match( '/--iti-flag-count:\s*(\d+)/', $source, $count ) ) {
		throw new RuntimeException( 'No --iti-flag-count in the vendored stylesheet.' );
	}

	preg_match_all( '/\.iti__([a-z]{2})\s*\{\s*--iti-flag-offset:\s*(-?\d+);?\s*\}/', $source, $flags, PREG_SET_ORDER );

	if ( count( $flags ) !== (int) $count[1] ) {
		throw new RuntimeException( sprintf( 'Expected %d flags, found %d.', (int) $count[1], count( $flags ) ) );
	}

	$flag = '.send4-iti .iti__flag:not(.iti__globe):not(.iti__loading)';
	$css  = "/* GENERATED by bin/build-flag-css.php from the vendored intl-tel-input. Do not edit. */\n";
	$css .= ".send4-iti{--send4-flag-w:20px;--send4-flag-h:15px}\n";
	$css .= $flag . '{width:var(--send4-flag-w)!important;height:var(--send4-flag-h)!important;box-sizing:border-box!important;padding:0!important;';
	$css .= 'background-image:image-set(url(../lib/intl-tel-input/img/flags.webp) 1x,url(../lib/intl-tel-input/img/flags-2x.webp) 2x)!important;';
	$css .= 'background-repeat:no-repeat!important;';
	$css .= 'background-size:calc(' . (int) $count[1] . ' * var(--send4-flag-w)) var(--send4-flag-h)!important;';
	$css .= "background-position:calc(var(--send4-flag-i,-100) * var(--send4-flag-w) * -1) 0!important}\n";

	foreach ( $flags as $match ) {
		$css .= '.send4-iti .iti__' . $match[1] . '{--send4-flag-i:' . abs( (int) $match[2] ) . "}\n";
	}

	return $css;
}

if ( ! defined( 'SEND4_FLAG_CSS_AS_LIBRARY' ) ) {
	$send4_root = dirname( __DIR__ );

	file_put_contents( $send4_root . '/public/css/phone-flags.css', send4_build_flag_css( $send4_root ) );
	echo "Wrote public/css/phone-flags.css\n";
}
